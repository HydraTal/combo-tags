#!/usr/bin/env node
// Regenerates src/main/resources/com/combotags/variant_sort.tsv: the default variant order (VariantSort, which
// ItemIndex.variants serves), baked from the filter lab's rules.js variantTypes and variantSort on the webviewer
// branch. Every rule matches Jagex's internal item names, which the plugin doesn't have at runtime, so each item's
// value under every sort rule is worked out here and the plugin only compares them.
//
// The table: a "@steps" line naming the rules in priority order, each as id:direction:unmatched, then one row per item
// that any rule matches: id, internal name, and each matched rule as rule=value (a flag rule as just its id). A rule an
// item doesn't match takes its unmatched value: a number, or "plain" for Count's: 0 (empty) when the item's name is
// another version's without a bracketed count ("Amulet of glory" beside "Amulet of glory(4)") or says uncharged,
// otherwise unlimited. That one depends on the other versions being sorted, so VariantSort works it out at runtime.
//
// Usage (after editing the lab's rules.js, or a game update and `npm run data` in the lab):
//   node scripts/gen-variant-sort.mjs [--lab <path/to/combo-tags-webviewer/webviewer>]
// --lab defaults to the combo-tags-webviewer worktree next to this repo.
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { fileURLToPath } from 'url';

const args = process.argv.slice(2);
const flag = args.indexOf('--lab');
const lab = flag >= 0 ? args[flag + 1]
	: path.join(path.dirname(fileURLToPath(import.meta.url)), '../../combo-tags-webviewer/webviewer');
for (const f of ['data/items.js', 'rules.js', 'engine.js'])
{
	if (!fs.existsSync(path.join(lab, f)))
	{
		console.error(`can't find the filter lab's ${f} in ${lab}; run \`npm run data\` in the lab or pass --lab`);
		process.exit(1);
	}
}

// The lab's files assign to `window`; run them in one context, as the lab page does.
const ctx = vm.createContext({ performance, console });
ctx.window = ctx;
for (const f of ['data/items.js', 'rules.js', 'engine.js'])
{
	vm.runInContext(fs.readFileSync(path.join(lab, f), 'utf8'), ctx, { filename: f });
}
const E = ctx.FilterEngine, R = ctx.RULES, data = ctx.ITEM_DATA;
const prep = E.prepare(data);
const index = E.build(prep, R);

const types = new Map(R.variantTypes.map(t => [t.id, t]));
const steps = R.variantSort.order.map(id =>
{
	const t = types.get(id);
	if (!t) throw new Error(`variantSort.order names ${id}, which isn't a variantType`);
	return t;
});
const kindOf = t => t.dir === 'az' || t.dir === 'za' ? 'tag' : t.value || t.unmatched != null ? 'value' : 'flag';
// Count's unmatched reads the other versions' names; it's the only context-dependent value the plugin knows how to work
// out at runtime. Any other function would be baked wrong, so stop instead.
const PLAIN = new Set(['count']);
const unmatchedOf = t =>
{
	if (typeof t.unmatched === 'function')
	{
		if (!PLAIN.has(t.id)) throw new Error(`${t.id}: an unmatched function VariantSort can't evaluate; teach it, or bake a number`);
		return 'plain';
	}
	const u = t.unmatched ?? 0;
	if (!Number.isFinite(u)) throw new Error(`${t.id}: unmatched ${u} isn't a finite number`);
	return String(u);
};
if (R.variantSort.tiebreak !== 'name') throw new Error(`variantSort.tiebreak ${R.variantSort.tiebreak}: VariantSort only does 'name'`);

// A folded recolor (fold.recolors): the one variantType test that reads the lab's index rather than the item.
const folded = id => { const c = prep.canon(id); return index.merge.has(index.statBase.get(c) ?? c); };
const tctx = { ...prep.ctx, folded, isPlain: () => false };

const rows = [];
const hits = new Map(steps.map(t => [t.id, 0]));
for (const item of prep.named)
{
	if (index.excluded.has(item.id)) continue; // never a variant
	const cells = [];
	for (const t of steps)
	{
		if (!E.ruleMatches(t, item, tctx)) continue;
		const m = (t.name && item.name.match(t.name)) || (t.key && item.key.match(t.key)) || [];
		const kind = kindOf(t);
		if (kind === 'flag')
		{
			cells.push(t.id);
		}
		else if (kind === 'value')
		{
			const v = t.value ? t.value(m, item, tctx) : 1;
			if (!Number.isInteger(v)) throw new Error(`${t.id} on ${item.key}: value ${v} isn't an integer`);
			cells.push(`${t.id}=${v}`);
		}
		else
		{
			const tag = String(t.tag?.(m, item, tctx) ?? '');
			if (/[\t=]/.test(tag)) throw new Error(`${t.id} on ${item.key}: tag ${JSON.stringify(tag)} has a tab or "="`);
			cells.push(`${t.id}=${tag}`);
		}
		hits.set(t.id, hits.get(t.id) + 1);
	}
	if (cells.length) rows.push(`${item.id}\t${item.key}\t${cells.join('\t')}`);
}

const header = [
	`# Generated by scripts/gen-variant-sort.mjs from the filter lab's rules.js (variantTypes, variantSort) and its`
		+ ` RuneLite ${data.version} / ${data.dump} item data. Do not edit by hand.`,
	'# @steps: the sort rules in priority order, as id:direction:unmatched (a number, or "plain": see VariantSort).',
	'# Then: id, internal name, and each rule the item matches (a flag as its id, a value or tag as id=value).',
	'@steps\t' + steps.map(t => `${t.id}:${t.dir}:${unmatchedOf(t)}`).join('\t'),
];
const target = new URL('../src/main/resources/com/combotags/variant_sort.tsv', import.meta.url);
fs.writeFileSync(target, header.concat(rows).join('\n') + '\n');
for (const t of steps) console.log(String(hits.get(t.id)).padStart(6), `${t.id} (${t.dir})`);
console.log(String(rows.length).padStart(6), 'items ->', fileURLToPath(target));

// The parity check for VariantSortParityTest: every entry with two or more variants, in the order the lab's engine
// serves them (E.variants), each variant with its display name (the test hands VariantSort the names, then the
// shuffled ids, and wants this order back).
const golden = [];
for (const e of index.entries)
{
	const vars = E.variants(index, e.id);
	if (vars.length < 2) continue;
	golden.push([e.id, ...vars.flatMap(v => [v, prep.name(v) ?? ''])].join('\t'));
}
const goldenTarget = new URL('../src/test/resources/com/combotags/variant_sort_golden.tsv', import.meta.url);
fs.mkdirSync(new URL('.', goldenTarget), { recursive: true });
fs.writeFileSync(goldenTarget, [
	'# Generated by scripts/gen-variant-sort.mjs: every entry with 2+ variants, as the filter lab serves them.',
	'# entry id, then each variant as id, display name, in served order. Do not edit by hand.',
].concat(golden).join('\n') + '\n');
console.log(String(golden.length).padStart(6), 'entries ->', fileURLToPath(goldenTarget));
